// GET /health : server and database check
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ message: "Database is not responding." });
  }
});

app.use("/api/records", require("./routes/records"));

// Unknown routes
app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

// Error handler (4 parameters)
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed" || error instanceof SyntaxError) {
    return res.status(400).json({ message: "Malformed JSON in the request body." });
  }
  if (error.status >= 400 && error.status < 500) {
    return res.status(400).json({ message: "The request could not be read." });
  }
  console.error("Unexpected error:", error);
  res.status(500).json({ message: "Unexpected server error. Please try again." });
});

const databaseUrl = process.env.DATABASE_URL || "";
if (!databaseUrl || databaseUrl.includes("PASTE_")) {
  console.warn("WARNING: DATABASE_URL is not set. Edit the .env file (see README).");
}

const port = process.env.PORT || 3000;
app.listen(port, "0.0.0.0", () => {
  console.log(`Server listening on port ${port}`);
});
